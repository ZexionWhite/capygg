type MessagePool = readonly string[];

const previousMessageIndexes = new Map<MessagePool, number>();

export function pickMessage(pool: MessagePool): string {
	if (pool.length === 0) return '';

	if (pool.length === 1) return pool[0]!;

	const previousIndex = previousMessageIndexes.get(pool);
	let index: number;

	do {
		index = Math.floor(Math.random() * pool.length);
	} while (index === previousIndex);

	previousMessageIndexes.set(pool, index);

	return pool[index]!;
}

